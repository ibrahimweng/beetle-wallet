/* build-figma-plugin.mjs — builds the Figma plugin from the site's own files.
   Run from anywhere:

     node glyphs/tools/build-figma-plugin.mjs          write glyphs/figma-plugin/dist/
     node glyphs/tools/build-figma-plugin.mjs --check  fail if dist/ no longer matches its sources,
                                                       or any icon would reach Figma broken

   Nothing is forked. The panel is the site's engine, library, store, toolbar,
   grid, sidebar and whole-library panel, read from glyphs/src and rolled into
   one page with the plugin's own few files in glyphs/figma-plugin/ui. The data
   is glyphs/data as it is, stored compressed and written as base64. The panel
   cannot load other files, so dist/ui.html holds everything. No dependencies:
   each module becomes a function that returns its exports, the way the root
   build.js rolls up the wallet.

   dist/ is committed, so the plugin can be imported into Figma without a
   build, and --check is what keeps it honest: CI goes red when a change on
   the site has not reached the plugin. */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { resolve, dirname, relative } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import { gzipSync, gunzipSync } from 'zlib';
import { createRequire } from 'module';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');                 // glyphs/
const plugin = resolve(root, 'figma-plugin');
const dist = resolve(plugin, 'dist');
const read = p => readFileSync(resolve(root, p), 'utf8');
const check = process.argv.includes('--check');

/* the plugin's data, and every other file, lives under this made-up address;
   the panel's fetch answers it from the page itself and never goes out */
const DATA_BASE = 'https://plugin.beetle-glyphs.invalid/';
const BUDGET = 10 * 1024 * 1024;                  // PLAN.md: fail above 10 MB, far under Figma's reported 15 MB

/* ---------- the modules: from the entry, every relative import, dependencies first ---------- */
const IMPORT = /^import\s+(?:\{([^}]*)\}|\*\s+as\s+(\w+))\s+from\s+'([^']+)';?[ \t]*$/gm;
function bundle(entry) {
  const order = [], seen = new Map();
  const visit = (file, chain) => {
    if (seen.get(file) === 'done') return;
    if (seen.get(file) === 'open') throw new Error('an import cycle: ' + [...chain, file].map(f => relative(root, f)).join(' -> '));
    seen.set(file, 'open');
    const code = readFileSync(file, 'utf8');
    for (const m of code.matchAll(IMPORT)) {
      if (!m[3].startsWith('.')) throw new Error(`${relative(root, file)} imports '${m[3]}', which is not a file in the repository`);
      visit(resolve(dirname(file), m[3]), [...chain, file]);
    }
    seen.set(file, 'done'); order.push(file);
  };
  visit(entry, []);
  const key = file => 'M$' + relative(root, file).replace(/[^\w]/g, '_');
  const wrap = file => {
    const exports = [];
    let code = readFileSync(file, 'utf8').replace(IMPORT, (_, names, ns, spec) => {
      const from = key(resolve(dirname(file), spec));
      return ns ? `const ${ns} = ${from};` : `const {${names.replace(/\bas\b/g, ':')}} = ${from};`;
    });
    code = code.replace(/^export\s+(const|let|async function|function)\s+(\w+)/gm, (_, kind, name) => { exports.push(name); return `${kind} ${name}`; });
    code = code.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (_, names) => { for (const n of names.split(',').map(s => s.trim()).filter(Boolean)) exports.push(n.split(/\s+as\s+/).pop()); return ''; });
    if (/^\s*export\b/m.test(code)) throw new Error('an export the plugin build cannot read, in ' + relative(root, file));
    if (/^\s*import\b/m.test(code)) throw new Error('an import the plugin build cannot read, in ' + relative(root, file));
    return `/* ${relative(root, file)} */\nconst ${key(file)} = (function () {\n${code}\nreturn { ${exports.join(', ')} };\n})();\n`;
  };
  return { files: order.map(f => relative(root, f)), code: order.map(wrap).join('\n') };
}

/* ---------- the data, as the site serves it ---------- */
function dataFiles() {
  const icons = JSON.parse(read('data/icons.json'));
  const out = [];
  /* the drawings' paths become addresses of their own: Figma's panel has no page address to read a relative path against */
  for (const [file, path] of Object.entries(icons.drawings || {})) { out.push({ url: DATA_BASE + path, path }); icons.drawings[file] = DATA_BASE + path; }
  out.unshift({ url: DATA_BASE + 'data/icons.json', path: 'data/icons.json', text: JSON.stringify(icons) });
  for (const f of out) if (f.text == null) f.text = read(f.path);
  return out;
}

const NOTICE = () => `Beetle Glyphs for Figma. Built from glyphs/ in https://github.com/ibrahimweng/beetle-wallet
by glyphs/tools/build-figma-plugin.mjs. Do not edit this file; edit the sources and build again.

The icons are copied with these notices, and the notices stay with them.

========================================================================
${read('LICENSE-core.txt').trim()}

========================================================================
${read('LICENSE-keyline.txt').trim()}

========================================================================
The app glyphs and the parametric icons belong to the Beetle wallet design.`;

const safeScript = (s, what) => { if (/<\/script/i.test(s)) throw new Error(`${what} holds </script, which would end the panel's script early`); return s; };
const BLOB = /<script type="application\/gzip-base64" data-url="([^"]+)">([^<]*)<\/script>/g;

/* the page, with each data file's bytes left as a slot; --check compares
   slots by what they unpack to, so another zlib can never fail the check */
function page() {
  const mod = bundle(resolve(plugin, 'ui/main.js'));
  const css = read('src/styles/globals.css') + '\n' + read('figma-plugin/ui/plugin.css');
  if (/<\/style/i.test(css)) throw new Error('the stylesheet holds </style');
  const data = dataFiles();
  const notice = NOTICE();
  if (/--!?>/.test(notice)) throw new Error('a licence notice would end the comment at the top of ui.html early');
  const text = (id, s) => `<script type="text/plain" id="${id}">${safeScript(s.replace(/&/g, '&amp;').replace(/</g, '&lt;'), id)}</script>`;
  const html = `<!--\n${notice}\n-->
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Beetle Glyphs</title>
<style>
${css}
</style>
</head>
<body>
${data.map(f => `<script type="application/gzip-base64" data-url="${f.url}">\u0000${f.url}\u0000</script>`).join('\n')}
${text('licence-core', read('LICENSE-core.txt'))}
${text('licence-four', read('LICENSE-keyline.txt'))}
<script>
${safeScript(read('vendor/clipper.js'), 'vendor/clipper.js')}
</script>
<script type="module">
${safeScript(mod.code, 'the panel bundle')}
</script>
</body>
</html>
`;
  return { html, data, files: mod.files };
}
const fill = (html, data) => html.replace(/\u0000([^\u0000]+)\u0000/g, (_, url) => gzipSync(Buffer.from(data.find(f => f.url === url).text), { level: 9 }).toString('base64'));
const slots = html => html.replace(BLOB, (_, url) => `<script type="application/gzip-base64" data-url="${url}">\u0000${url}\u0000</script>`);

/* the main thread runs in Figma's sandbox: keep to syntax it has always read */
function code() {
  const src = read('figma-plugin/code.js');
  for (const [re, what] of [[/\?\.[^\d]/, 'optional chaining (?.)'], [/\?\?/, 'nullish coalescing (??)'], [/^\s*(import|export)\b/m, 'a module import or export']]) if (re.test(src)) throw new Error(`figma-plugin/code.js uses ${what}, which Figma's sandbox may not read`);
  return `/* Beetle Glyphs for Figma, the main thread. Built from glyphs/figma-plugin/code.js; do not edit. */\n${src}`;
}
function manifest() {
  const m = JSON.parse(read('figma-plugin/manifest.json'));
  const fail = msg => { throw new Error('figma-plugin/manifest.json: ' + msg); };
  if (m.main !== 'code.js' || m.ui !== 'ui.html') fail('main must be code.js and ui ui.html');
  if (!m.networkAccess || JSON.stringify(m.networkAccess.allowedDomains) !== '["none"]') fail('networkAccess.allowedDomains must be ["none"]: the plugin never goes out');
  if (m.documentAccess !== 'dynamic-page') fail('documentAccess must be "dynamic-page"');
  if ('id' in m && !/^\d+$/.test(String(m.id))) fail('id must be the number Figma gives at first publish, or left out');
  if (/keyline/i.test(JSON.stringify(m))) fail('the plugin is never named after Keyline');
  return JSON.stringify(m, null, 2) + '\n';
}

function build() {
  const p = page();
  return { 'manifest.json': manifest(), 'code.js': code(), html: p.html, data: p.data, files: p.files };
}

/* ---------- write ---------- */
const out = build();
if (!check) {
  mkdirSync(dist, { recursive: true });
  const ui = fill(out.html, out.data);
  if (ui.length > BUDGET) { console.error(`ui.html is ${(ui.length / 1048576).toFixed(2)} MB, over the ${BUDGET / 1048576} MB budget`); process.exit(1); }
  writeFileSync(resolve(dist, 'manifest.json'), out['manifest.json']);
  writeFileSync(resolve(dist, 'code.js'), out['code.js']);
  writeFileSync(resolve(dist, 'ui.html'), ui);
  console.log(`figma-plugin/dist: ui.html ${(ui.length / 1048576).toFixed(2)} MB, from ${out.files.length} modules and ${out.data.length} data files`);
  process.exit(0);
}

/* ---------- check ---------- */
let failures = 0;
const ok = (pass, what, detail = '') => { console.log(`  ${pass ? '✓' : '✗'} ${what}${pass || !detail ? '' : ' — ' + detail}`); if (!pass) failures++; };
const stale = 'run `node glyphs/tools/build-figma-plugin.mjs` and commit glyphs/figma-plugin/dist/';
console.log('figma plugin: dist/ matches its sources');
for (const f of ['manifest.json', 'code.js']) { const p = resolve(dist, f); ok(existsSync(p) && readFileSync(p, 'utf8') === out[f], `dist/${f}`, stale); }
const uiPath = resolve(dist, 'ui.html');
const built = existsSync(uiPath) ? readFileSync(uiPath, 'utf8') : '';
ok(slots(built) === out.html, 'dist/ui.html: the page, the engine, the components and the styles', stale);
const blobs = new Map([...built.matchAll(BLOB)].map(m => [m[1], m[2]]));
for (const f of out.data) {
  let same = false; try { same = gunzipSync(Buffer.from(blobs.get(f.url) || '', 'base64')).toString() === f.text; } catch { /* not there, or not gzip */ }
  ok(same, `dist/ui.html: ${f.path}`, stale);
}
ok(built.length <= BUDGET, `ui.html is ${(built.length / 1048576).toFixed(2)} MB, within the ${BUDGET / 1048576} MB budget`);
ok(built.startsWith('<!--') && built.includes(read('LICENSE-core.txt').trim()) && built.includes(read('LICENSE-keyline.txt').trim()), 'both licence notices are in full at the top of ui.html');
ok(!/fonts\.googleapis|https?:\/\/(?!plugin\.beetle-glyphs\.invalid|github\.com|www\.w3\.org|opensource\.org)[a-z]/i.test(slots(built).replace(/<!--[\s\S]*?-->/, '').replace(/<script>[\s\S]*?<\/script>/, '')), 'the panel asks for nothing from the network');

/* every icon, in every style and both corners, the way the panel draws it for Figma */
console.log('figma plugin: every icon reaches Figma whole');
{
  const require = createRequire(import.meta.url);
  const CL = require('../vendor/clipper.js');
  globalThis.location = globalThis.location || { href: DATA_BASE };
  const realFetch = globalThis.fetch;
  globalThis.fetch = async url => { const f = out.data.find(d => d.url === String(url)); if (!f) return realFetch(url); return { ok: true, status: 200, json: async () => JSON.parse(f.text) }; };
  const L = await import(pathToFileURL(resolve(root, 'src/lib/library.js')).href);
  const E = await import(pathToFileURL(resolve(root, 'src/lib/engine.js')).href);
  const { figmaSvg, problems } = await import(pathToFileURL(resolve(plugin, 'ui/figma-svg.js')).href);
  E.useClipper(CL); // as in the panel, where Clipper is loaded before the engine
  await L.loadLibrary(DATA_BASE + 'data/icons.json');
  const sets = {}; for (const e of L.lib.entries) sets[e.set] = (sets[e.set] || 0) + 1;
  await L.loadDrawings('fills');
  ok(sets.core === 1854 && sets.four === 1366 && sets.beetle === 85 && sets.scenarios === 127, `every icon ships: ${L.lib.entries.length} (core ${sets.core}, four-style ${sets.four}, app ${sets.beetle}, scenarios ${sets.scenarios})`);
  let n = 0; const bad = [];
  for (const corners of ['rounded', 'sharp']) for (const weight of E.WEIGHTS) {
    await L.loadDrawings(L.drawingFile(weight, corners));
    const state = { P: { ...E.DEF, weight, corners }, edits: {} };
    for (const e of L.lib.entries) {
      const prims = L.primsOf(e.key, state);
      const svg = figmaSvg(prims, state.P, { CL, color: '#123456' }); n++;
      const p = problems(svg);
      if (!prims.length) p.push('no parts');
      if (!/<path /.test(svg)) p.push('nothing to draw');
      if (p.length) bad.push(`${e.key} ${weight} ${corners}: ${p.join(', ')}`);
    }
  }
  ok(!bad.length, `${n.toLocaleString('en-US')} drawings, each with no mask, no filter, no currentColor and no NaN`, bad.slice(0, 5).join(' | '));
  globalThis.fetch = realFetch;
}

/* the main thread against a recording stand-in for figma */
console.log('figma plugin: code.js against a stand-in for Figma');
{
  const { run } = await import(pathToFileURL(resolve(plugin, 'test/code.mjs')).href);
  const r = await run(resolve(dist, 'code.js'));
  for (const [pass, what, detail] of r) ok(pass, what, detail);
}

if (failures) { console.error(`\n${failures} check${failures > 1 ? 's' : ''} failed`); process.exit(1); }
console.log('\nthe Figma plugin matches its sources');
